    private void botaoCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoCadastrarActionPerformed
        fis.RG = Integer.parseInt(this.textRG.getText());
        fis.CPF = Integer.parseInt(this.textCPF.getText());
        fis.Endereco = this.textEndereco.getText();
        fis.cidade = this.textCidade.getText();
        fis.estado = this.textEstado.getText();
        
        JOptionPane.showMessageDialog(null, "Dados Cadastrados com Sucesso");
        
        this.textRG.setText("");
        this.textCPF.setText("");
        this.textEndereco.setText("");
        this.textCidade.setText("");
        this.textEstado.setText("");
    }//GEN-LAST:event_botaoCadastrarActionPerformed


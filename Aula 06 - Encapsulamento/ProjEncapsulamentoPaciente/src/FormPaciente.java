    private void botaoCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoCadastrarActionPerformed
        //Alocando os dados nos atributos pelos campos de texto
        paciente.nome = this.textNomePaciente.getText();
        paciente.ano_nascimento = Integer.parseInt(this.textAnoNascimento.getText());
        
        //acessando o método set para os atributros privados
        paciente.setProfissao(this.textProfissao.getText());
        paciente.setValor_Consulta(Double.parseDouble(this.textValorConsulta.getText()));
        JOptionPane.showMessageDialog(null,"Dados Cadastrados");
        
        this.textNomePaciente.setText("");
        this.textAnoNascimento.setText("");
        this.textProfissao.setText("");
        this.textValorConsulta.setText("");
    }//GEN-LAST:event_botaoCadastrarActionPerformed

    private void botaoExibirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoExibirActionPerformed
        this.textNomePaciente.setText(paciente.nome);
        this.textAnoNascimento.setText("" + paciente.ano_nascimento);
        //atribuindo aos campos de texto o retorno dos métodos get dos atributos private.
        this.textProfissao.setText("" + paciente.getProfissao());
        this.textValorConsulta.setText("" + paciente.getValor_Consulta());
    }//GEN-LAST:event_botaoExibirActionPerformed


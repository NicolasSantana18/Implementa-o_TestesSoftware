    private void botaoCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoCadastrarActionPerformed
        try{    
            ci.RaioBase = Double.parseDouble(this.textRaio.getText());
            ci.Altura = Double.parseDouble(this.textAltura.getText());

            JOptionPane.showMessageDialog(null, "Dados Cadastrados com Sucesso!!");

            this.textRaio.setText("");
            this.textAltura.setText("");
        }
        catch (NumberFormatException e) {
        
            JOptionPane.showMessageDialog(null, "Digite somente Números / erro:" + e);
        
        }
    }//GEN-LAST:event_botaoCadastrarActionPerformed

